    public static function httpStatus(string $code): int
    {
        return self::CATALOG[$code][0] ?? 500;
    }

    public static function message(string $code): string
    {
        return self::CATALOG[$code][1] ?? 'Terjadi kesalahan';
    }

    public static function codeForHttpStatus(int $httpStatus): string
    {
        return match ($httpStatus) {
            400     => 'ERR_COMMON_007',
            401     => 'ERR_AUTH_002',
            403     => 'ERR_COMMON_003',
            404     => 'ERR_COMMON_002',
            405     => 'ERR_COMMON_006',
            409     => 'ERR_COMMON_008',
            413     => 'ERR_FILE_001',
            422     => 'ERR_COMMON_001',
